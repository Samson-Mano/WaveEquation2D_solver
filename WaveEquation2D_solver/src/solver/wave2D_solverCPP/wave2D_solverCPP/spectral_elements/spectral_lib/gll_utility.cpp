void gll_utility::evaluate_lagrange_1D(double x,
	const std::vector<double>& nodes,
	std::vector<double>& L,
	std::vector<double>& dL)
{
	int n = nodes.size();

	L.resize(n);
	dL.resize(n);

	for (int i = 0; i < n; i++)
	{
		double li = 1.0;
		double dli = 0.0;

		for (int j = 0; j < n; j++)
		{
			if (j == i) continue;

			double denom = nodes[i] - nodes[j];
			li *= (x - nodes[j]) / denom;
		}

		// Derivative
		for (int j = 0; j < n; j++)
		{
			if (j == i) continue;

			double term = 1.0 / (nodes[i] - nodes[j]);

			for (int k = 0; k < n; k++)
			{
				if (k == i || k == j) continue;

				term *= (x - nodes[k]) / (nodes[i] - nodes[k]);
			}

			dli += term;
		}

		L[i] = li;
		dL[i] = dli;
	}

}




